const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const { randomUUID } = require('node:crypto');
const api = require('../src/index.cjs');
const example = require('../examples/comments.config.cjs');

test('real local API pins generated PNG, validates mutations, transfers bundles and closes without resurrection', { timeout: 60000 }, async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'deckloom-comment-api-'));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const project = { ...example, root, comments: { ...example.comments, root: path.join(root, '.comments') } };
  const rendered = await api.createRenderer(project).render({ deckId: 'demo' });
  assert.equal(rendered.status, 'succeeded', JSON.stringify(rendered.diagnostics));
  const server = api.createReviewServer(project);
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(() => new Promise(resolve => server.close(resolve)));
  const base = `http://127.0.0.1:${server.address().port}`;
  const html = await (await fetch(base)).text();
  const config = JSON.parse(html.match(/window\.deckloomConfig = (.*?);<\/script>/)[1]);
  assert(config.comments); assert(html.includes('/api/comments/ui.js'));
  assert.equal((await fetch(base + '/api/comments/ui.js')).status, 200);
  assert.equal((await fetch(base + '/api/comments/ui.css')).status, 200);
  const get = async suffix => (await fetch(base + '/api/comments' + suffix)).json();
  const post = (operation, extraHeaders = {}) => fetch(base + '/api/comments?deck=demo', { method: 'POST', headers: {
    'Content-Type': 'application/json', 'X-Deckloom-Comment-Token': config.commentToken, ...extraHeaders }, body: JSON.stringify({ operation, viewerSlideId: 'cover' }) });
  const initial = await get('?deck=demo'); assert.equal(initial.document.threads.length, 0);
  const current = await get('/context?deck=demo&slide=cover');
  assert.equal(current.context.slideId, 'cover'); assert.equal(current.context.width, 960);
  const portrait = await get('/context?deck=demo&slide=portrait');
  assert.equal(portrait.context.width, 540); assert.equal(portrait.context.height, 960);
  const png = Buffer.from(await (await fetch(base + current.imageUrl)).arrayBuffer());
  assert.equal(api.comments.hash(png), current.context.pngSha256);
  const create = api.comments.operation('create', { threadId: randomUUID(), messageId: randomUUID(), context: current.context, x: .27, y: .64, text: 'Замечание — «точно здесь»' });
  assert.equal((await post(create, { 'X-Deckloom-Comment-Token': 'invalid' })).status, 403);
  assert.equal((await post(create, { 'Sec-Fetch-Site': 'cross-site' })).status, 403);
  assert.equal((await post({ ...create, author: { id: 'pretend' } })).status, 400);
  assert.equal((await post(create)).status, 200);
  assert.equal((await (await post(create)).json()).repeated, true);
  const oldBundle = Buffer.from(await (await fetch(base + '/api/comments/export?deck=demo&format=zip')).arrayBuffer());
  assert.equal(api.comments.importBundle(oldBundle).document.threads.length, 1);
  assert.equal((await api.createRenderer(project).render({ deckId: 'demo' })).status, 'succeeded');
  const regenerated = await get('/context?deck=demo&slide=cover');
  assert.notEqual(regenerated.context.id, current.context.id);
  assert.equal((await (await post(create)).json()).repeated, true, 'uncertain retry remains idempotent after a new generation');
  assert.equal((await post({ ...create, operationId: randomUUID(), threadId: randomUUID(), messageId: randomUUID() })).status, 409, 'an old draft never silently targets a new generation');
  const replies = ['Ответ А', 'Ответ Б'].map(text => api.comments.operation('reply', { threadId: create.threadId, messageId: randomUUID(), text }));
  const concurrent = await Promise.all(replies.map(reply => post(reply)));
  for (let i = 0; i < concurrent.length; i++) if (!concurrent[i].ok) assert.equal((await post(replies[i])).status, 200);
  let state = await get('?deck=demo'); assert.equal(state.document.threads[0].messages.length, 3);
  assert.equal((await post(api.comments.operation('edit', { threadId: create.threadId, messageId: create.messageId, expectedRevision: 1, text: 'Устаревшая правка' }))).status, 409);
  const close = api.comments.operation('close', { threadId: create.threadId, expectedRevision: state.document.threads[0].revision });
  assert.equal((await post(close)).status, 200);
  state = await get('?deck=demo'); assert.equal(state.document.threads.length, 0); assert.equal(state.document.contexts.length, 0);
  const removed = await fetch(base + `/api/comments/image?deck=demo&sha=${current.context.pngSha256}`); assert.equal(removed.status, 404);
  const imported = await fetch(base + '/api/comments/import?deck=demo', { method: 'POST', headers: {
    'Content-Type': 'application/zip', 'X-Deckloom-Comment-Token': config.commentToken, 'X-Deckloom-Expected-Token': state.token }, body: oldBundle });
  assert.equal(imported.status, 200, await imported.text());
  state = await get('?deck=demo'); assert.equal(state.document.threads.length, 0);
  assert.equal((await fetch(base + current.imageUrl)).status, 200, 'closing a comment copy never removes the generated slide image');
  const disk = await fs.readdir(path.join(root, '.comments/images')); assert.deepEqual(disk, []);
  const sourceHtml = await (await fetch(base + '/api/decks')).json();
  assert.equal(sourceHtml.decks[0].slides.length, 2);
});
